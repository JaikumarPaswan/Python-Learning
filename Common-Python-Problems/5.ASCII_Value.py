#Decimal and ASCII-Character

# Python ord() function returns the Unicode code of a given single character. It is a modern encoding standard that aims to represent every character in every language.
# Unicode includes:
    # ASCII characters (first 128 code points)
    # Emojis, currency symbols, accented characters, etc.

# The numeric value assigned to an ASCII character, which is the same in the first 128 codes of Unicode (0–127), is commonly referred to as its decimal value or decimal code

print(ord("a"))
print(ord('€'))



# chr() function returns a string representing a character whose Unicode code point is the integer specified.
print(chr(97))



